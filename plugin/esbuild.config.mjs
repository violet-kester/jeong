import esbuild from 'esbuild';
import process from 'process';
import fs from 'node:fs';
import path from 'node:path';
import { builtinModules } from 'node:module';
import { fontFaces, inlineWorker } from './build-tools.mjs';

const banner = `/*
THIS IS A GENERATED/BUNDLED FILE BY ESBUILD
if you want to view the source, please visit https://github.com/violet-kester/jeong
*/
`;

const prod = process.argv[2] === 'production';

// Where the built plugin goes. To build straight into a vault, create local.json
// (not committed) with {"pluginDir": "<vault>/.obsidian/plugins/jeong"}.
const local = fs.existsSync('local.json') ? JSON.parse(fs.readFileSync('local.json', 'utf8')) : {};
const outDir = local.pluginDir || 'build';
fs.mkdirSync(outDir, { recursive: true });

// Copy the manifest and styles (with fonts) next to main.js, and mark the folder for the Hot Reload plugin
const copyStatic = {
	name: 'copy-static',
	setup(build) {
		build.onEnd(() => {
			fs.copyFileSync('manifest.json', path.join(outDir, 'manifest.json'));
			// BRAT (for installing on phones) reads the manifest at the repo root; keep it in sync
			fs.copyFileSync('manifest.json', path.join('..', 'manifest.json'));
			fs.writeFileSync(path.join(outDir, 'styles.css'), `${fontFaces()}\n\n${fs.readFileSync('styles.css', 'utf8')}`);
			if (!prod) fs.writeFileSync(path.join(outDir, '.hotreload'), '');
		});
	},
};

const context = await esbuild.context({
	banner: {
		js: banner,
	},
	entryPoints: ['src/main.ts'],
	bundle: true,
	external: [
		'obsidian',
		'electron',
		'@codemirror/autocomplete',
		'@codemirror/collab',
		'@codemirror/commands',
		'@codemirror/language',
		'@codemirror/lint',
		'@codemirror/search',
		'@codemirror/state',
		'@codemirror/view',
		'@lezer/common',
		'@lezer/highlight',
		'@lezer/lr',
		...builtinModules,
	],
	format: 'cjs',
	target: 'es2021',
	logLevel: 'info',
	sourcemap: prod ? false : 'inline',
	treeShaking: true,
	outfile: path.join(outDir, 'main.js'),
	minify: prod,
	plugins: [inlineWorker(prod), copyStatic],
});

if (prod) {
	await context.rebuild();
	process.exit(0);
} else {
	await context.watch();
}
