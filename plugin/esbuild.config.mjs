import esbuild from 'esbuild';
import process from 'process';
import fs from 'node:fs';
import path from 'node:path';
import { builtinModules } from 'node:module';

const banner = `/*
THIS IS A GENERATED/BUNDLED FILE BY ESBUILD
if you want to view the source, please visit https://github.com/violet-kester/jeong
*/
`;

const prod = process.argv[2] === 'production';

// Where the built plugin goes. To build straight into a vault, create local.json
// (not committed) with {"pluginDir": "<vault>/.obsidian/plugins/jeong"}.
const local = fs.existsSync('local.json') ? JSON.parse(fs.readFileSync('local.json', 'utf8')) : {};
const outDir = local.pluginDir || 'build';
fs.mkdirSync(outDir, { recursive: true });

// Copy the manifest and styles next to main.js, and mark the folder for the Hot Reload plugin
const copyStatic = {
	name: 'copy-static',
	setup(build) {
		build.onEnd(() => {
			for (const file of ['manifest.json', 'styles.css']) {
				fs.copyFileSync(file, path.join(outDir, file));
			}
			if (!prod) fs.writeFileSync(path.join(outDir, '.hotreload'), '');
		});
	},
};

// Files imported as "./something?worker" are bundled on their own (as an ES module)
// and inlined into main.js as text, because a plugin ships as one main.js file.
// The plugin then starts them as Web Workers from a blob URL.
const inlineWorker = {
	name: 'inline-worker',
	setup(build) {
		build.onResolve({ filter: /\?worker$/ }, (args) => ({
			path: path.resolve(args.resolveDir, args.path.replace(/\?worker$/, '') + '.ts'),
			namespace: 'inline-worker',
		}));
		build.onLoad({ filter: /.*/, namespace: 'inline-worker' }, async (args) => {
			const result = await esbuild.build({
				entryPoints: [args.path],
				bundle: true,
				write: false,
				format: 'esm',
				platform: 'browser',
				target: 'es2022',
				minify: prod,
				logLevel: 'warning',
				metafile: true,
			});
			return {
				contents: `export default ${JSON.stringify(result.outputFiles[0].text)};`,
				loader: 'js',
				watchFiles: Object.keys(result.metafile.inputs).map((file) => path.resolve(file)),
			};
		});
	},
};

const context = await esbuild.context({
	banner: {
		js: banner,
	},
	entryPoints: ['src/main.ts'],
	bundle: true,
	external: [
		'obsidian',
		'electron',
		'@codemirror/autocomplete',
		'@codemirror/collab',
		'@codemirror/commands',
		'@codemirror/language',
		'@codemirror/lint',
		'@codemirror/search',
		'@codemirror/state',
		'@codemirror/view',
		'@lezer/common',
		'@lezer/highlight',
		'@lezer/lr',
		...builtinModules,
	],
	format: 'cjs',
	target: 'es2021',
	logLevel: 'info',
	sourcemap: prod ? false : 'inline',
	treeShaking: true,
	outfile: path.join(outDir, 'main.js'),
	minify: prod,
	plugins: [inlineWorker, copyStatic],
});

if (prod) {
	await context.rebuild();
	process.exit(0);
} else {
	await context.watch();
}
