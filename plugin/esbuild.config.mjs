import esbuild from 'esbuild';
import process from 'process';
import fs from 'node:fs';
import path from 'node:path';
import { builtinModules } from 'node:module';

const banner = `/*
THIS IS A GENERATED/BUNDLED FILE BY ESBUILD
if you want to view the source, please visit https://github.com/violet-kester/jeong
*/
`;

const prod = process.argv[2] === 'production';

// Where the built plugin goes. To build straight into a vault, create local.json
// (not committed) with {"pluginDir": "<vault>/.obsidian/plugins/jeong"}.
const local = fs.existsSync('local.json') ? JSON.parse(fs.readFileSync('local.json', 'utf8')) : {};
const outDir = local.pluginDir || 'build';
fs.mkdirSync(outDir, { recursive: true });

// Fonts are bundled into styles.css so they work offline (all SIL Open Font License; see assets/fonts).
// Hahmlet and Gowun are subset to Latin + Korean; IBM Plex Mono ships unmodified (its name is reserved).
const FONTS = [
	{ family: 'Jeong Hahmlet', file: 'Hahmlet-Latin.woff2', weight: '100 900' },
	{ family: 'Jeong Gowun Batang', file: 'GowunBatang-Regular.woff2', weight: '400' },
	{ family: 'Jeong Gowun Batang', file: 'GowunBatang-Bold.woff2', weight: '700' },
	{ family: 'Jeong Gowun Dodum', file: 'GowunDodum-Regular.woff2', weight: '400' },
	{ family: 'IBM Plex Mono', file: 'IBMPlexMono-Regular.ttf', weight: '400' },
	{ family: 'IBM Plex Mono', file: 'IBMPlexMono-Medium.ttf', weight: '500' },
];

function fontFaces() {
	return FONTS.map(({ family, file, weight }) => {
		const data = fs.readFileSync(path.join('assets/fonts', file)).toString('base64');
		const format = file.endsWith('.woff2') ? 'woff2' : 'truetype';
		const mime = file.endsWith('.woff2') ? 'font/woff2' : 'font/ttf';
		return `@font-face { font-family: "${family}"; font-weight: ${weight}; font-style: normal; font-display: swap; src: url(data:${mime};base64,${data}) format("${format}"); }`;
	}).join('\n');
}

// Copy the manifest and styles (with fonts) next to main.js, and mark the folder for the Hot Reload plugin
const copyStatic = {
	name: 'copy-static',
	setup(build) {
		build.onEnd(() => {
			fs.copyFileSync('manifest.json', path.join(outDir, 'manifest.json'));
			// BRAT (for installing on phones) reads the manifest at the repo root; keep it in sync
			fs.copyFileSync('manifest.json', path.join('..', 'manifest.json'));
			fs.writeFileSync(path.join(outDir, 'styles.css'), `${fontFaces()}\n\n${fs.readFileSync('styles.css', 'utf8')}`);
			if (!prod) fs.writeFileSync(path.join(outDir, '.hotreload'), '');
		});
	},
};

// Files imported as "./something?worker" are bundled on their own (as an ES module)
// and inlined into main.js as text, because a plugin ships as one main.js file.
// The plugin then starts them as Web Workers from a blob URL.
const inlineWorker = {
	name: 'inline-worker',
	setup(build) {
		build.onResolve({ filter: /\?worker$/ }, (args) => ({
			path: path.resolve(args.resolveDir, args.path.replace(/\?worker$/, '') + '.ts'),
			namespace: 'inline-worker',
		}));
		build.onLoad({ filter: /.*/, namespace: 'inline-worker' }, async (args) => {
			const result = await esbuild.build({
				entryPoints: [args.path],
				bundle: true,
				write: false,
				format: 'esm',
				platform: 'browser',
				target: 'es2022',
				minify: prod,
				logLevel: 'warning',
				metafile: true,
			});
			return {
				contents: `export default ${JSON.stringify(result.outputFiles[0].text)};`,
				loader: 'js',
				watchFiles: Object.keys(result.metafile.inputs).map((file) => path.resolve(file)),
			};
		});
	},
};

const context = await esbuild.context({
	banner: {
		js: banner,
	},
	entryPoints: ['src/main.ts'],
	bundle: true,
	external: [
		'obsidian',
		'electron',
		'@codemirror/autocomplete',
		'@codemirror/collab',
		'@codemirror/commands',
		'@codemirror/language',
		'@codemirror/lint',
		'@codemirror/search',
		'@codemirror/state',
		'@codemirror/view',
		'@lezer/common',
		'@lezer/highlight',
		'@lezer/lr',
		...builtinModules,
	],
	format: 'cjs',
	target: 'es2021',
	logLevel: 'info',
	sourcemap: prod ? false : 'inline',
	treeShaking: true,
	outfile: path.join(outDir, 'main.js'),
	minify: prod,
	plugins: [inlineWorker, copyStatic],
});

if (prod) {
	await context.rebuild();
	process.exit(0);
} else {
	await context.watch();
}
